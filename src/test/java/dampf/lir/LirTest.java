package dampf.lir;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.List;
import org.junit.jupiter.api.Test;

/** LIR: blocks from the text, the printer, the parser and the verifier on small hand-written pieces. */
class LirTest {
    private static String ins(String m, String op) {
        return LPrinter.instr(new LInstr(m, op, null, true));
    }

    private static String ins8(String m, String op) {
        return LPrinter.instr(new LInstr(m, op, null, false));
    }

    private static String text(String... lines) {
        return String.join("\n", lines) + "\n";
    }

    @Test
    void blocksAreCutAtLabelsAndBranches() {
        LUnit u = LParser.parse(text(
                "        .segment \"CODE\"",
                ".proc f",
                ins("lda", "z:dampf_frame+0"),
                ins("beq", "b2"),
                ins("inc", "a"),
                "b2:",
                "                                    ; a note",
                ins("rtl", null),
                ".endproc"));
        LFunction f = u.functions().getFirst();
        assertEquals(3, f.blocks().size());
        LBlock b0 = f.blocks().get(0);
        LBlock b1 = f.blocks().get(1);
        LBlock b2 = f.blocks().get(2);
        assertNull(b1.label());
        assertEquals("b2", b2.label().name());
        assertEquals(List.of(b2, b1), b0.successors());
        assertEquals(b2, b0.target());
        assertEquals(List.of(b2), b1.successors());
        assertEquals(List.of(), b2.successors());
        assertEquals(List.of(), LVerifier.verify(u));
    }

    @Test
    void unnamedLabels() {
        LUnit u = LParser.parse(text(
                ".proc f",
                ins("bne", ":+"),
                ins("inc", "a"),
                ":",
                ins("rtl", null),
                ".endproc"));
        LFunction f = u.functions().getFirst();
        assertEquals(f.blocks().get(2), f.blocks().get(0).target());
    }

    @Test
    void theTextReadsBackTheSame() {
        LSourceLine header = new LSourceLine("; a.c:3   x = 1;");
        header.setCycles(9, true);
        String t = text(
                "; Generated by dampf",
                "",
                "        .p816",
                "        .import dampf_mul16, dampf_udiv16",
                "R0  = dampf_regs+0                  ; runtime routine registers",
                "        .segment \"BSS\"",
                "_x:                         .res    2    ; int x",
                "_t:                         ; const table",
                "        .byte   $01,$02",
                "        .word   .loword(_t+2)",
                "        .byte   ^(_t+2), 0",
                ".proc f",
                LPrinter.sourceLine(header),
                "        .dbg    line, \"a.c\", 3",
                LPrinter.instr(new LInstr("lda", "#$0001", "x = 1", true)),
                ins("jsl", "dampf_mul16"),
                ins("sep", "#$20"),
                ins8("lda", "#$01"),
                ins("rep", "#$20"),
                ins("rtl", null),
                ".endproc");
        LUnit u = LParser.parse(t);
        assertEquals(t, LPrinter.print(u));
        assertEquals(List.of(), LVerifier.verify(u));
        LInstr lda8 = u.functions().getFirst().instrs().get(3);
        assertTrue(!lda8.m16() && lda8.length() == 2);
    }

    @Test
    void theVerifierFindsProblems() {
        List<String> e = LVerifier.verify(LParser.parse(text(
                ".proc f",
                "a1:",
                ins("bne", "nowhere"),
                "a1:",
                ins("lda", "#$0001"),
                ".endproc")));
        assertTrue(e.stream().anyMatch(s -> s.contains("a1 is defined twice")), e.toString());
        assertTrue(e.stream().anyMatch(s -> s.contains("not in the function")), e.toString());
        assertTrue(e.stream().anyMatch(s -> s.contains("runs off the end")), e.toString());
    }

    @Test
    void theVerifierFollowsTheWidthAcrossBlocks() {
        // 8 bit on one way in, 16 on the other: the LDA #imm after the join has no fixed width
        List<String> e = LVerifier.verify(LParser.parse(text(
                ".proc f",
                ins("beq", "j"),
                ins("sep", "#$20"),
                "j:",
                ins("lda", "#$0001"),
                ins("rtl", null),
                ".endproc")));
        assertTrue(e.stream().anyMatch(s -> s.contains("depends on the way in")), e.toString());
        // written for 16 bit, runs in 8 (a branch from 8-bit code to a label where 16 was assumed)
        List<String> e2 = LVerifier.verify(LParser.parse(text(
                ".proc f",
                ins("sep", "#$20"),
                ins8("bra", "j"),
                ins8("rep", "#$20"),
                "j:",
                ins("lda", "#$0001"),
                ins("rtl", null),
                ".endproc")));
        assertTrue(e2.stream().anyMatch(s -> s.contains("written for 16-bit A but runs with 8")), e2.toString());
    }

    @Test
    void unknownLinesAreErrors() {
        assertThrows(IllegalArgumentException.class, () -> LParser.line("        .macro foo"));
        assertThrows(IllegalArgumentException.class, () -> LParser.line("x: lda #1"));
    }

    @Test
    void aBranchOverAJumpBecomesTheInverseBranch() {
        // as a switch writes it: compare, branch over the jump to the case, next comparison
        LUnit u = LParser.parse(text(
                ".proc f",
                ins("cmp", "#$0001"),
                "        bne     @L0",
                "        jmp     case1",
                "@L0:",
                ins("cmp", "#$0002"),
                ins("rtl", null),
                "case1:",
                ins("rtl", null),
                ".endproc"));
        LFunction f = u.functions().getFirst();
        // the parser does not know which branches the code generator marked; mark them as it would
        List<LItem> items = new java.util.ArrayList<>();
        for (LItem i : f.items()) {
            items.add(i instanceof LInstr in && (in.mnemonic().equals("bne") || in.mnemonic().equals("jmp"))
                    ? new LInstr(in.mnemonic(), in.operand(), null, true, true, true) : i);
        }
        f.rebuild(items);
        BranchRelax.run(f);
        List<String> code = f.instrs().stream().map(LInstr::toString).toList();
        assertEquals(List.of("cmp #$0001", "beq case1", "cmp #$0002", "rtl", "rtl"), code);
        assertEquals(List.of(), LVerifier.verify(u));
    }

    @Test
    void aStoreAndLoadIntoXBecomesTax() {
        LUnit u = LParser.parse(text(
                ".proc f",
                ins("sta", "z:dampf_frame+4"),
                ins("ldx", "z:dampf_frame+4"),
                ins("sta", "z:dampf_frame+6"),
                ins("ldy", "z:dampf_frame+6"),
                ins("sep", "#$20"),
                ins8("sta", "z:dampf_frame+8"),
                ins8("ldx", "z:dampf_frame+8"),   // 8-bit A: TAX would copy the high byte B
                ins8("rep", "#$20"),
                ins("rtl", null),
                ".endproc"));
        LFunction f = u.functions().getFirst();
        Peephole.run(f);
        List<String> code = f.instrs().stream().map(LInstr::toString).toList();
        assertEquals(List.of("sta z:dampf_frame+4", "tax", "sta z:dampf_frame+6", "tay", "sep #$20",
                "sta z:dampf_frame+8", "ldx z:dampf_frame+8", "rep #$20", "rtl"), code);
    }
}
