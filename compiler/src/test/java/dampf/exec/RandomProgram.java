package dampf.exec;

import java.util.ArrayList;
import java.util.List;
import java.util.Random;

/**
 * Generates random C programs within the subset that dampf supports, for differential testing
 * against gcc. Every program is free of undefined behaviour by construction (the PC side also
 * runs with the undefined behaviour sanitizer, which would report a mistake here):
 * <ul>
 * <li>divisors are made odd ({@code | 1}), so never zero;</li>
 * <li>shift counts are masked to the width of the promoted operand;</li>
 * <li>left shifts and wide multiplications are done in {@code uint32_t}, where overflow wraps;</li>
 * <li>a multiplication in int has one operand narrowed to 8 bits, so it cannot overflow;</li>
 * <li>{@code int32_t} values only come from conversions, never from int arithmetic that could
 *     overflow.</li>
 * </ul>
 */
final class RandomProgram {
    private static final String[] TYPES = {"int8_t", "uint8_t", "int16_t", "uint16_t", "int32_t", "uint32_t"};
    private static final String[] NARROW = {"int8_t", "uint8_t", "int16_t", "uint16_t"};

    private final Random rnd;
    private final List<String> vars = new ArrayList<>();
    private final List<String> types = new ArrayList<>();

    RandomProgram(long seed) {
        this.rnd = new Random(seed);
    }

    String generate(int globals, int statements) {
        StringBuilder c = new StringBuilder("/* generated by RandomProgram */\n#include <stdint.h>\n\n");
        for (int i = 0; i < globals; i++) {
            String t = TYPES[rnd.nextInt(TYPES.length)];
            vars.add("v" + i);
            types.add(t);
            c.append(t).append(" v").append(i).append(" = ").append(initial(t)).append(";\n");
        }
        c.append("\nvoid test_main(void)\n{\n");
        for (int i = 0; i < statements; i++) {
            statement(c, "    ", 0);
        }
        c.append("}\n");
        return c.toString();
    }

    private void statement(StringBuilder c, String indent, int depth) {
        int kind = rnd.nextInt(10);
        if (kind == 0 && depth < 2) {
            c.append(indent).append("if (").append(expr(3)).append(") {\n");
            statement(c, indent + "    ", depth + 1);
            c.append(indent).append("} else {\n");
            statement(c, indent + "    ", depth + 1);
            c.append(indent).append("}\n");
        } else if (kind == 1 && depth < 2) {
            // a bounded loop: the counter is a fresh variable in its own block
            int n = 1 + rnd.nextInt(4);
            c.append(indent).append("{\n").append(indent).append("    uint8_t k;\n");
            c.append(indent).append("    for (k = 0; k < ").append(n).append("; k++) {\n");
            statement(c, indent + "        ", depth + 1);
            c.append(indent).append("    }\n").append(indent).append("}\n");
        } else {
            int target = rnd.nextInt(vars.size());
            String op = rnd.nextInt(4) == 0 ? new String[] {"+=", "-=", "^=", "|=", "&="}[rnd.nextInt(5)] : "=";
            String t = types.get(target);
            if (!op.equals("=") && t.equals("int32_t")) {
                op = "="; // a compound assignment on int32_t could overflow
            }
            c.append(indent).append(vars.get(target)).append(' ').append(op).append(" (").append(t).append(")(")
                    .append(expr(3)).append(");\n");
        }
    }

    /** An expression whose value fits in its promoted type without overflow. */
    private String expr(int depth) {
        if (depth == 0 || rnd.nextInt(4) == 0) {
            return leaf();
        }
        String a = expr(depth - 1);
        String b = expr(depth - 1);
        return switch (rnd.nextInt(17)) {
            // + and - on values narrowed to 16 bits cannot overflow int; in uint32_t they wrap
            case 0 -> "(" + narrow(a) + " + " + narrow(b) + ")";
            case 1 -> "(" + narrow(a) + " - " + narrow(b) + ")";
            case 2 -> "((uint32_t)(" + a + ") + (uint32_t)(" + b + "))";
            case 3 -> "((uint32_t)(" + a + ") - (uint32_t)(" + b + "))";
            case 4 -> "(" + narrow(a) + " * (" + (rnd.nextBoolean() ? "int8_t" : "uint8_t") + ")(" + b + "))";
            case 5 -> "((uint32_t)(" + a + ") * (uint32_t)(" + b + "))";
            case 6 -> "(" + narrow(a) + " / (" + narrow(b) + " | 1))";
            case 7 -> "(" + narrow(a) + " % (" + narrow(b) + " | 1))";
            case 8 -> "((uint32_t)(" + a + ") / ((uint32_t)(" + b + ") | 1u))";
            case 9 -> "((uint32_t)(" + a + ") % ((uint32_t)(" + b + ") | 1u))";
            case 10 -> "((uint32_t)(" + a + ") << ((" + b + ") & 31))";
            case 11 -> "(" + narrow(a) + " >> ((" + b + ") & 15))";
            case 12 -> "((int32_t)(" + a + ") >> ((" + b + ") & 31))";
            case 13 -> "(" + a + " " + new String[] {"&", "|", "^"}[rnd.nextInt(3)] + " " + b + ")";
            case 14 -> {
                // plain variables half of the time: their comparisons take the 8- and 16-bit paths
                String l = rnd.nextBoolean() ? vars.get(rnd.nextInt(vars.size())) : a;
                String r = rnd.nextBoolean() ? vars.get(rnd.nextInt(vars.size())) : b;
                yield "(" + l + " " + new String[] {"<", "<=", ">", ">=", "==", "!="}[rnd.nextInt(6)] + " " + r + ")";
            }
            case 15 -> "(" + a + (rnd.nextBoolean() ? " && " : " || ") + b + ")";
            default -> "(" + a + " ? " + b + " : " + expr(depth - 1) + ")";
        };
    }

    private String leaf() {
        return switch (rnd.nextInt(5)) {
            case 0 -> rnd.nextBoolean() ? Integer.toString(rnd.nextInt(200) - 100)
                    : "(" + EDGES[rnd.nextInt(EDGES.length)] + ")";
            case 1 -> "(~" + vars.get(rnd.nextInt(vars.size())) + ")";
            case 2 -> "(!" + vars.get(rnd.nextInt(vars.size())) + ")";
            default -> vars.get(rnd.nextInt(vars.size()));
        };
    }

    private String narrow(String e) {
        return "(" + NARROW[rnd.nextInt(NARROW.length)] + ")(" + e + ")";
    }

    /** Values at the edges of the types, where overflow and sign handling go wrong. */
    private static final long[] EDGES = {0, 1, -1, 127, 128, -128, 255, 256, 32767, 32768, -32768, -32767, 65535, 65536,
            2147483647, -2147483647};

    private String initial(String t) {
        if (rnd.nextInt(3) == 0) {
            long v = EDGES[rnd.nextInt(EDGES.length)];
            return "(" + t + ")" + (v < 0 ? "(" + v + ")" : v + (v > 2147483647 ? "u" : ""));
        }
        return switch (t) {
            case "int8_t" -> Integer.toString(rnd.nextInt(256) - 128);
            case "uint8_t" -> Integer.toString(rnd.nextInt(256));
            case "int16_t" -> Integer.toString(rnd.nextInt(65536) - 32768);
            case "uint16_t" -> Integer.toString(rnd.nextInt(65536));
            case "int32_t" -> Integer.toString(Math.max(rnd.nextInt(), -Integer.MAX_VALUE)); // -2147483648 would be a long literal
            default -> Long.toString(rnd.nextLong() & 0xFFFFFFFFL) + "u";
        };
    }
}
